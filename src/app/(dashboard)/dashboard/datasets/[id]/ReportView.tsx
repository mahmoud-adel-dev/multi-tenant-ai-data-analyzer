"use client";

/**
 * Report view — renders the verified ReportPlan with print-to-PDF support.
 * Numbers come exclusively from the deterministic engine; the optional AI
 * narrative is clearly labeled.
 */
import type { ReportPlan, ReportBlock, Metric } from "@/types/analytics";

interface Props {
  plan: ReportPlan;
  narrativeSummary: string | null;
}

export default function ReportView({ plan, narrativeSummary }: Props) {
  return (
    <div>
      <div className="no-print" style={{ display: "flex", justifyContent: "flex-end", marginBottom: "14px" }}>
        <button onClick={() => window.print()} style={printBtn}>
          Export as PDF (Print)
        </button>
      </div>

      <article className="print-area" style={reportStyle}>
        <header style={{ borderBottom: "2px solid var(--border-color)", paddingBottom: "18px", marginBottom: "26px" }}>
          <h1 style={{ fontSize: "24px", fontWeight: 800, color: "var(--text-primary)" }}>{plan.title}</h1>
          <p style={{ fontSize: "12px", color: "var(--text-muted)", marginTop: "6px" }}>
            Generated {new Date().toLocaleDateString()} · All figures computed deterministically from the source dataset.
          </p>
        </header>

        {narrativeSummary && (
          <aside
            aria-label="AI-generated executive narrative"
            style={{
              background: "var(--accent-light)",
              borderLeft: "3px solid var(--accent-primary)",
              borderRadius: "10px",
              padding: "14px 16px",
              marginBottom: "24px",
            }}
          >
            <div style={{ fontSize: "11px", fontWeight: 700, textTransform: "uppercase", letterSpacing: "0.07em", color: "var(--accent-primary)", marginBottom: "6px" }}>
              AI Executive Narrative (generated over verified results)
            </div>
            <p style={{ fontSize: "13.5px", color: "var(--text-secondary)", lineHeight: 1.7 }}>{narrativeSummary}</p>
          </aside>
        )}

        {plan.sections.map((section) => (
          <section key={section.key} style={{ marginBottom: "30px" }} aria-label={section.title}>
            <h2 style={{ fontSize: "16px", fontWeight: 700, color: "var(--text-primary)", marginBottom: "12px", display: "flex", alignItems: "center", gap: "8px" }}>
              {section.title}
            </h2>
            <SectionBlocks blocks={section.blocks} />
          </section>
        ))}

        <footer style={{ borderTop: "1px solid var(--border-subtle)", paddingTop: "14px", fontSize: "11px", color: "var(--text-muted)", marginTop: "34px" }}>
          This report was generated by the AIDL analytics platform. Statistics are computed by a deterministic
          engine (Polars / SciPy / scikit-learn); no language model computed any number in this document.
          Narrative sections (if present) are AI-generated explanations over verified results and are labeled as such.
        </footer>
      </article>
    </div>
  );
}

function SectionBlocks({ blocks }: { blocks: Array<ReportBlock | Record<string, unknown>> }) {
  return (
    <div style={{ display: "flex", flexDirection: "column", gap: "12px" }}>
      {blocks.map((b, i) => {
        const block = b as ReportBlock;
        switch (block.kind) {
          case "paragraph":
            return (
              <p key={i} style={{ fontSize: "13.5px", color: "var(--text-secondary)", lineHeight: 1.7, whiteSpace: "pre-line" }}>
                {block.text}
              </p>
            );
          case "bullets":
            return (
              <ul key={i} style={{ paddingLeft: "20px", display: "flex", flexDirection: "column", gap: "5px" }}>
                {(block.items ?? []).map((item, j) => (
                  <li key={j} style={{ fontSize: "13.5px", color: "var(--text-secondary)", lineHeight: 1.55 }}>
                    {item}
                  </li>
                ))}
              </ul>
            );
          case "metrics":
            return <MetricGrid key={i} metrics={(block.metrics ?? []) as Metric[]} />;
          case "table":
            return <ReportTable key={i} title={block.title ?? null} columns={block.columns ?? []} rows={block.rows ?? []} />;
          case "warning":
            return (
              <div key={i} style={{ background: "rgba(245,158,11,0.08)", border: "1px solid rgba(245,158,11,0.4)", borderRadius: "10px", padding: "12px 14px", fontSize: "13px", color: "#f59e0b" }}>
                ⚠ {block.text}
              </div>
            );
          default:
            return null;
        }
      })}
    </div>
  );
}

function MetricGrid({ metrics }: { metrics: Metric[] }) {
  return (
    <div className="kpi-grid">
      {metrics.map((m) => (
        <div
          key={m.metricId}
          title={`Aggregation: ${m.provenance.aggregation}${m.provenance.sourceColumns.length ? ` of ${m.provenance.sourceColumns.join(", ")}` : ""}`}
          style={{
            background: "var(--bg-card)",
            border: "1px solid var(--border-subtle)",
            borderRadius: "12px",
            padding: "14px",
            breakInside: "avoid",
          }}
        >
          <div style={{ fontSize: "11.5px", fontWeight: 600, color: "var(--text-secondary)", minHeight: "28px" }}>{m.label}</div>
          <div style={{ fontSize: "19px", fontWeight: 800, color: "var(--text-primary)" }}>
            {m.value === null ? "—" : m.value.toLocaleString(undefined, { maximumFractionDigits: 2 })}
            {m.unit ? <span style={{ fontSize: "12px", fontWeight: 500, color: "var(--text-muted)" }}> {m.unit}</span> : null}
          </div>
        </div>
      ))}
    </div>
  );
}

function ReportTable({ title, columns, rows }: { title: string | null; columns: string[]; rows: string[][] }) {
  if (columns.length === 0) return null;
  return (
    <div>
      {title && <p style={{ fontSize: "13px", fontWeight: 600, color: "var(--text-primary)", marginBottom: "8px" }}>{title}</p>}
      <div style={{ overflowX: "auto", border: "1px solid var(--border-subtle)", borderRadius: "10px" }}>
        <table style={{ width: "100%", borderCollapse: "collapse", fontSize: "12.5px" }}>
          <thead>
            <tr style={{ background: "var(--bg-secondary)" }}>
              {columns.map((c) => (
                <th key={c} style={{ textAlign: "left", padding: "9px 12px", fontSize: "11px", textTransform: "uppercase", letterSpacing: "0.05em", color: "var(--text-muted)", whiteSpace: "nowrap" }}>
                  {c}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.slice(0, 50).map((row, i) => (
              <tr key={i}>
                {row.map((cell, j) => (
                  <td key={j} style={{ padding: "8px 12px", borderBottom: "1px solid var(--border-subtle)", whiteSpace: "nowrap", maxWidth: "420px", overflow: "hidden", textOverflow: "ellipsis" }}>
                    {cell}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

const reportStyle: React.CSSProperties = {
  background: "var(--bg-card)",
  border: "1px solid var(--border-subtle)",
  borderRadius: "16px",
  padding: "32px",
  maxWidth: "900px",
};

const printBtn: React.CSSProperties = {
  padding: "9px 18px",
  borderRadius: "8px",
  background: "var(--brand-gradient)",
  color: "#fff",
  fontWeight: 600,
  fontSize: "13px",
  border: "none",
  cursor: "pointer",
};
